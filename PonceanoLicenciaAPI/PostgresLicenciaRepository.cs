using System.Data;
using Npgsql;

namespace PonceanoLicenciaAPI;

public sealed class PostgresLicenciaRepository : ILicenciaRepository, IAsyncDisposable
{
    private readonly NpgsqlDataSource _dataSource;
    private const string Schema = """
        CREATE TABLE IF NOT EXISTS licencias (
            id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            correousuario text NOT NULL UNIQUE,
            estadolicencia text NOT NULL CHECK (estadolicencia IN ('Activo', 'Pendiente', 'Vencido')),
            fechavencimiento timestamp with time zone NOT NULL,
            codigotransaccionpago text NOT NULL UNIQUE
        );
        """;

    public PostgresLicenciaRepository(IConfiguration configuration, ILogger<PostgresLicenciaRepository> logger)
    {
        var connectionString = configuration.GetConnectionString("Licencias");
        if (string.IsNullOrWhiteSpace(connectionString))
        {
            if (connectionString is not null)
                logger.LogWarning("ConnectionStrings__Licencias está vacía; se intentará usar DATABASE_URL.");
            connectionString = configuration["DATABASE_URL"];
        }

        if (string.IsNullOrWhiteSpace(connectionString))
        {
            const string mensaje = "Configure ConnectionStrings__Licencias o DATABASE_URL de PostgreSQL con un valor no vacío en el servicio y entorno de Railway correctos.";
            logger.LogError("{Mensaje}", mensaje);
            throw new InvalidOperationException(mensaje);
        }

        _dataSource = NpgsqlDataSource.Create(NormalizarCadenaConexion(connectionString));
    }

    private static string NormalizarCadenaConexion(string connectionString)
    {
        if (!Uri.TryCreate(connectionString, UriKind.Absolute, out var uri) ||
            uri.Scheme is not ("postgres" or "postgresql"))
            return new NpgsqlConnectionStringBuilder(connectionString) { SslMode = SslMode.VerifyFull }.ConnectionString;

        var userInfo = uri.UserInfo.Split(':', 2);
        if (userInfo.Length != 2 || string.IsNullOrWhiteSpace(uri.Host) || string.IsNullOrWhiteSpace(uri.AbsolutePath.Trim('/')))
            throw new InvalidOperationException("DATABASE_URL no es una URL PostgreSQL válida.");
        var query = System.Web.HttpUtility.ParseQueryString(uri.Query);
        var builder = new NpgsqlConnectionStringBuilder
        {
            Host = uri.Host,
            Port = uri.IsDefaultPort ? 5432 : uri.Port,
            Username = Uri.UnescapeDataString(userInfo[0]),
            Password = Uri.UnescapeDataString(userInfo[1]),
            Database = Uri.UnescapeDataString(uri.AbsolutePath.Trim('/')),
            SslMode = SslMode.VerifyFull,
            Timeout = 15,
            CommandTimeout = 15
        };
        return builder.ConnectionString;
    }

    public async Task EnsureCreatedAsync(CancellationToken cancellationToken)
    {
        await using var connection = await _dataSource.OpenConnectionAsync(cancellationToken);
        await using var command = new NpgsqlCommand(Schema, connection);
        await command.ExecuteNonQueryAsync(cancellationToken);
    }

    public async Task<Licencia?> BuscarAsync(string correo, CancellationToken cancellationToken)
    {
        const string sql = "SELECT id, correousuario, estadolicencia, fechavencimiento, codigotransaccionpago FROM licencias WHERE correousuario = @correo";
        await using var command = _dataSource.CreateCommand(sql);
        command.Parameters.AddWithValue("correo", correo);
        await using var reader = await command.ExecuteReaderAsync(cancellationToken);
        return await reader.ReadAsync(cancellationToken) ? LeerLicencia(reader) : null;
    }

    public async Task<Licencia> ActivarAsync(string correo, DateTimeOffset vencimiento, string codigo, CancellationToken cancellationToken)
    {
        await using var connection = await _dataSource.OpenConnectionAsync(cancellationToken);
        await using var transaction = await connection.BeginTransactionAsync(IsolationLevel.Serializable, cancellationToken);
        try
        {
            await using (var buscarTransaccion = new NpgsqlCommand(
                "SELECT id, correousuario, estadolicencia, fechavencimiento, codigotransaccionpago FROM licencias WHERE codigotransaccionpago = @codigo FOR UPDATE",
                connection, transaction))
            {
                buscarTransaccion.Parameters.AddWithValue("codigo", codigo);
                await using var reader = await buscarTransaccion.ExecuteReaderAsync(cancellationToken);
                if (await reader.ReadAsync(cancellationToken))
                {
                    var existente = LeerLicencia(reader);
                    await reader.CloseAsync();
                    if (existente.CorreoUsuario != correo || existente.FechaVencimiento != vencimiento.ToUniversalTime())
                        throw new TransaccionDuplicadaException();
                    await transaction.CommitAsync(cancellationToken);
                    return existente;
                }
            }

            const string upsert = """
                INSERT INTO licencias (correousuario, estadolicencia, fechavencimiento, codigotransaccionpago)
                VALUES (@correo, 'Activo', @vencimiento, @codigo)
                ON CONFLICT (correousuario) DO UPDATE SET
                    estadolicencia = 'Activo', fechavencimiento = EXCLUDED.fechavencimiento,
                    codigotransaccionpago = EXCLUDED.codigotransaccionpago
                RETURNING id, correousuario, estadolicencia, fechavencimiento, codigotransaccionpago
                """;
            await using var command = new NpgsqlCommand(upsert, connection, transaction);
            command.Parameters.AddWithValue("correo", correo);
            command.Parameters.AddWithValue("vencimiento", vencimiento.ToUniversalTime());
            command.Parameters.AddWithValue("codigo", codigo);
            await using var resultado = await command.ExecuteReaderAsync(cancellationToken);
            if (!await resultado.ReadAsync(cancellationToken))
                throw new InvalidOperationException("PostgreSQL no devolvió la licencia activada.");
            var licencia = LeerLicencia(resultado);
            await resultado.CloseAsync();
            await transaction.CommitAsync(cancellationToken);
            return licencia;
        }
        catch (PostgresException ex) when (ex.SqlState == PostgresErrorCodes.UniqueViolation)
        {
            await transaction.RollbackAsync(CancellationToken.None);
            throw new TransaccionDuplicadaException();
        }
        catch
        {
            await transaction.RollbackAsync(CancellationToken.None);
            throw;
        }
    }

    private static Licencia LeerLicencia(NpgsqlDataReader reader) => new(
        reader.GetInt32(0), reader.GetString(1), reader.GetString(2), reader.GetFieldValue<DateTimeOffset>(3), reader.GetString(4));

    public ValueTask DisposeAsync() => _dataSource.DisposeAsync();
}
